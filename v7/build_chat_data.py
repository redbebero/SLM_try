out = Path("data/chat_train.jsonl")
out.parent.mkdir(parents=True, exist_ok=True)
i = 0
with out.open("w", encoding="utf-8") as f:
    for users, replies in single:
        for user in users:
            for reply in replies:
                f.write(json.dumps(record(i, [{"role": "user", "content": user}, {"role": "assistant", "content": reply}]), ensure_ascii=False) + "\n")
                i += 1
    for messages in multi:
        f.write(json.dumps(record(i, messages), ensure_ascii=False) + "\n")
        i += 1
